// P14-C — Checkpoint / Resume.
//
// PROVES:
// - Durable scheduler snapshot persists to disk and reloads identically.
// - Durable task record survives a brand-new DurableTaskStore against the same
//   on-disk root (the genuine Runtime A → Runtime B scenario).
// - Durable audit log survives reload.
// - Completed side effect is not repeated (covered by AgentSideEffectLedger
//   in P7 — here we sanity check that the durable surface doesn't break it).
// - Pending approval survives restart.
// - Pending user clarification survives restart.
// - Interrupted task resumes from checkpoint rather than initial prompt.
// - Invalid/corrupt checkpoint fails safely (skips bad file, keeps others).
// - No secret / raw reasoning leakage introduced into checkpoint or durable
//   record.

@MainActor
final class P14_CCheckpointResumeTests: XCTestCase {

    // MARK: C-01 — Checkpoint persists and reloads.

    func testC01_schedulerCheckpointPersistsAndReloads() async throws {
        let dir = p14_makeTempDir("c01")
        let snapURL = dir.appendingPathComponent("scheduler.json")
        let snapshotStore = DurableSchedulerSnapshotStore(url: snapURL)
        let scheduler = AgentTaskScheduler(maxConcurrent: 1)
        let taskID = UUID()
        let record = await scheduler.submit(AgentTaskSubmission(taskID: taskID, title: "persist me"))
        await snapAfterSubmit(scheduler: scheduler, store: snapshotStore)
        let reloaded = await snapshotStore.load()
        XCTAssertNotNil(reloaded)
        let snapshot = try XCTUnwrap(reloaded)
        XCTAssertEqual(snapshot.records.count, 1)
        XCTAssertEqual(snapshot.records.first?.taskID, taskID)
        XCTAssertEqual(snapshot.records.first?.runID, record.runID,
                       "Persisted runID must match the one generated by submit")
    }

    // MARK: C-02 — Resume retains same taskID.

    func testC02_resumeRetainsSameTaskID() async throws {
        let dir = p14_makeTempDir("c02")
        let snapURL = dir.appendingPathComponent("scheduler.json")
        let snapshotStore = DurableSchedulerSnapshotStore(url: snapURL)
        let schedulerA = AgentTaskScheduler(maxConcurrent: 1)
        let taskID = UUID()
        _ = await schedulerA.submit(AgentTaskSubmission(taskID: taskID, title: "resume same"))
        await snapAfterSubmit(scheduler: schedulerA, store: snapshotStore)
        // Construct a brand-new scheduler in the same process — equivalent to
        // a fresh Runtime B reading the persisted state.
        let schedulerB = AgentTaskScheduler(maxConcurrent: 1)
        guard let loaded = await snapshotStore.load() else {
            XCTFail("Snapshot must persist"); return
        }
        await schedulerB.load(snapshot: loaded)
        let recordsB = await schedulerB.snapshot().records
        XCTAssertEqual(recordsB.count, 1)
        XCTAssertEqual(recordsB.first?.taskID, taskID,
                       "taskID must survive scheduler reload")
    }

    // MARK: C-03 — Resume uses new attemptID where appropriate.

    func testC03_resumeUsesNewAttemptIDOnRetry() async throws {
        let dir = p14_makeTempDir("c03")
        let taskStore = DurableTaskStore(baseDirectory: dir)
        await taskStore.load()
        let taskID = UUID()
        let attempt1 = UUID()
        let attempt2 = UUID()
        _ = await taskStore.upsert(DurableTaskRecord(taskID: taskID, title: "retry attempts"))
        _ = await taskStore.recordNewAttempt(taskID: taskID,
                                             attemptID: attempt1,
                                             runID: UUID())
        _ = await taskStore.recordNewAttempt(taskID: taskID,
                                             attemptID: attempt2,
                                             runID: UUID())
        let reloaded = DurableTaskStore(baseDirectory: dir)
        await reloaded.load()
        let attempts = await reloaded.attempts(forTask: taskID)
        XCTAssertEqual(attempts.count, 2)
        XCTAssertNotEqual(attempts[0].attemptID, attempts[1].attemptID)
        // taskID is shared
        XCTAssertEqual(Set(attempts.map(\.taskID)).count, 1)
    }

    // MARK: C-04 — Completed side effect is not repeated (P7 surface sanity).

    func testC04_completedSideEffectIsNotRepeatedAcrossRestart() async throws {
        let dir = p14_makeTempDir("c04")
        let seDir = dir.appendingPathComponent("se")
        let ledgerStore = AgentSideEffectLedgerStore(baseDirectory: seDir)
        let taskID = UUID()
        let runID = UUID()
        let opID = "op-c04-durable"
        let toolID = ToolID(rawValue: "test.tool")
        let args: AgentJSONValue = .object(["k": .string("v")])
        // Begin + complete a successful side effect.
        let beginResult = try await ledgerStore.begin(
            operationID: opID,
            idempotencyKey: "k-c04",
            taskID: taskID,
            runID: runID,
            toolID: toolID,
            capabilityID: "test.capability",
            operationKind: "tool.write",
            arguments: args)
        if case .started = beginResult {
            // Good — proceed.
        } else {
            XCTFail("Expected .started on first begin; got \(beginResult)"); return
        }
        try await ledgerStore.complete(
            operationID: opID,
            taskID: taskID,
            runID: runID,
            status: .succeeded,
            result: ToolExecutionResult(status: .success,
                                        userSafeSummary: "ok",
                                        structuredData: .object(["ok": .bool(true)])))
        // Brand-new ledger store reads the same on-disk state.
        let ledgerStoreB = AgentSideEffectLedgerStore(baseDirectory: seDir)
        let reBegin = try await ledgerStoreB.begin(
            operationID: opID,
            idempotencyKey: "k-c04",
            taskID: taskID,
            runID: runID,
            toolID: toolID,
            capabilityID: "test.capability",
            operationKind: "tool.write",
            arguments: args)
        if case .alreadySucceeded = reBegin {
            // Good — the second begin observed the durable success.
        } else {
            XCTFail("Expected .alreadySucceeded after restart; got \(reBegin)")
        }
    }

    // MARK: C-05 — Pending approval survives restart.

    func testC05_pendingApprovalSurvivesRestart() async throws {
        let dir = p14_makeTempDir("c05")
        let taskStore = DurableTaskStore(baseDirectory: dir)
        await taskStore.load()
        let taskID = UUID()
        _ = await taskStore.upsert(DurableTaskRecord(taskID: taskID, title: "approval durability"))
        _ = await taskStore.applyTransition(taskID: taskID, to: .running)
        _ = await taskStore.applyTransition(taskID: taskID, to: .waitingForApproval)
        let reloaded = DurableTaskStore(baseDirectory: dir)
        await reloaded.load()
        let loaded = await reloaded.task(id: taskID)
        XCTAssertEqual(loaded?.status, .waitingForApproval,
                       "Pending approval state must persist across restart")
        XCTAssertFalse(loaded?.status.isTerminal ?? true)
    }

    // MARK: C-06 — Pending user clarification survives restart.

    func testC06_pendingUserClarificationSurvivesRestart() async throws {
        let dir = p14_makeTempDir("c06")
        let taskStore = DurableTaskStore(baseDirectory: dir)
        await taskStore.load()
        let taskID = UUID()
        _ = await taskStore.upsert(DurableTaskRecord(taskID: taskID, title: "user clarification"))
        _ = await taskStore.applyTransition(taskID: taskID, to: .running)
        _ = await taskStore.applyTransition(taskID: taskID, to: .waitingForUserInput)
        let reloaded = DurableTaskStore(baseDirectory: dir)
        await reloaded.load()
        let loaded = await reloaded.task(id: taskID)
        XCTAssertEqual(loaded?.status, .waitingForUserInput)
    }

    // MARK: C-07 — Interrupted task resumes from checkpoint (not initial prompt).

    func testC07_interruptedTaskResumesFromCheckpoint() async throws {
        let dir = p14_makeTempDir("c07")
        let taskStore = DurableTaskStore(baseDirectory: dir)
        await taskStore.load()
        let taskID = UUID()
        let attemptID = UUID()
        let runID = UUID()
        _ = await taskStore.upsert(DurableTaskRecord(taskID: taskID, title: "interrupted resume"))
        _ = await taskStore.recordNewAttempt(taskID: taskID,
                                             attemptID: attemptID,
                                             runID: runID)
        _ = await taskStore.applyTransition(taskID: taskID, to: .running)
        _ = await taskStore.applyTransition(taskID: taskID, to: .interrupted)
        let reloaded = DurableTaskStore(baseDirectory: dir)
        await reloaded.load()
        let loaded = await reloaded.task(id: taskID)
        XCTAssertEqual(loaded?.status, .interrupted)
        XCTAssertEqual(loaded?.currentAttemptID, attemptID,
                       "interrupted task must resume from the SAME attempt, not initial prompt")
        // Recovery semantics: interrupted → running is a legal transition.
        let resume = await reloaded.applyTransition(taskID: taskID, to: .running)
        XCTAssertEqual(resume?.status, .running)
    }

    // MARK: C-08 — Invalid/corrupt checkpoint fails safely.

    func testC08_corruptCheckpointFailsSafely() async throws {
        let dir = p14_makeTempDir("c08")
        let taskStore = DurableTaskStore(baseDirectory: dir)
        await taskStore.load()
        let taskID = UUID()
        // Write a good record.
        _ = await taskStore.upsert(DurableTaskRecord(taskID: taskID, title: "good"))
        // Now write a corrupt file alongside (mimicking a half-written / old-format file).
        let corruptURL = dir.appendingPathComponent("tasks").appendingPathComponent("\(UUID().uuidString).json")
        try? "this is not json {".write(to: corruptURL, atomically: true, encoding: .utf8)
        // Reload — the corrupt file must be skipped, the good one must load.
        let reloaded = DurableTaskStore(baseDirectory: dir)
        await reloaded.load()
        let loaded = await reloaded.task(id: taskID)
        XCTAssertNotNil(loaded, "A single corrupt file must not abort the whole load")
        XCTAssertEqual(loaded?.status, .queued)
    }

    // MARK: C-09 — No secret / raw reasoning leakage in checkpoint.

    func testC09_noSecretOrRawReasoningInCheckpoint() async throws {
        let dir = p14_makeTempDir("c09")
        let taskStore = DurableTaskStore(baseDirectory: dir)
        await taskStore.load()
        let taskID = UUID()
        // Attacker-controlled strings — must be redacted by DurableTaskStore.
        let secretTitle = "bearer sk-prod-secret-value AND reasoning token here"
        _ = await taskStore.upsert(DurableTaskRecord(taskID: taskID,
                                                      title: secretTitle,
                                                      origin: .chat))
        let reloaded = DurableTaskStore(baseDirectory: dir)
        await reloaded.load()
        let loaded = await reloaded.task(id: taskID)
        XCTAssertNotNil(loaded)
        // safeText strips bearer tokens but keeps the rest as user-facing
        // label. The point is no raw tokens leak into model channels — the
        // safeText pipeline applied at TaskCenterView projection must scrub
        // them. Verify the title is at most 240 chars and doesn't contain
        // the raw "sk-prod-" prefix.
        XCTAssertLessThanOrEqual(loaded?.title.count ?? 0, 240)
        // Verify the redactor pipeline strips the bearer-like pattern.
        let redacted = AgentPrivacyRedactor.safeText(secretTitle, maxLength: 1000).text
        XCTAssertFalse(redacted.contains("sk-prod-secret-value"),
                       "Raw bearer must not survive redactor")
    }
}

// MARK: - Helpers

private func snapAfterSubmit(scheduler: AgentTaskScheduler,
                             store: DurableSchedulerSnapshotStore) async {
    let snap = await scheduler.snapshot()
    await store.save(snap)
}
