/* global __dirname, process, Buffer */
/* Regenerate the embedded PNGs with: npx electron scripts/generate-tray-icon.cjs */
const { app, BrowserWindow, nativeImage } = require('electron');
const { readFileSync, writeFileSync } = require('node:fs');
const path = require('node:path');

const project = path.resolve(__dirname, '..');
const source = readFileSync(path.join(project, 'resources/tray/deskpetTemplate.svg'), 'utf8');

app.whenReady().then(async () => {
  const window = new BrowserWindow({ show: false, webPreferences: { sandbox: true, contextIsolation: true, nodeIntegration: false } });
  try {
    await window.loadURL('data:text/html,<meta charset="utf-8">');
    const entries = [];
    for (const [name, svg] of [['TEMPLATE', source], ['COLOR', source.replaceAll('black', '#5288dd')]]) {
      for (const scale of [1, 2]) {
        const size = 18 * scale;
        const data = await window.webContents.executeJavaScript(`(async () => {
          const image = new Image();
          image.src = ${JSON.stringify(`data:image/svg+xml;base64,${Buffer.from(svg).toString('base64')}`)};
          await image.decode();
          const canvas = document.createElement('canvas');
          canvas.width = ${size}; canvas.height = ${size};
          canvas.getContext('2d').drawImage(image, 0, 0, ${size}, ${size});
          return canvas.toDataURL('image/png');
        })()`);
        const decoded = nativeImage.createFromDataURL(data);
        if (decoded.isEmpty() || decoded.getSize().width !== size || decoded.getSize().height !== size) throw new Error('Generated tray PNG failed native decoding');
        entries.push(`export const TRAY_${name}_${scale}X = '${data.split(',')[1]}';`);
      }
    }
    writeFileSync(path.join(project, 'src/main/tray-icon-data.ts'), '// Generated by scripts/generate-tray-icon.cjs from resources/tray/deskpetTemplate.svg.\n// Embedded PNGs are bundled with the main process; no runtime asset path is needed.\n' + entries.join('\n') + '\n');
    process.stdout.write('Generated and natively decoded 18px/36px tray PNGs.\n');
  } finally {
    window.destroy();
    app.quit();
  }
}).catch((error) => { process.stderr.write(`${error.stack}\n`); app.exit(1); });
