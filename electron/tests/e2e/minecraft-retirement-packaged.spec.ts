import { _electron as electron, expect, test } from '@playwright/test';
import type { ElectronApplication } from '@playwright/test';
import { createHash, randomUUID } from 'node:crypto';
import { lstat, mkdir, mkdtemp, readFile, realpath, readdir, rm, writeFile } from 'node:fs/promises';
import { createRequire } from 'node:module';
import { createServer } from 'node:net';
import { tmpdir } from 'node:os';
import { dirname, join, resolve } from 'node:path';

const digest = (bytes: Buffer): string => createHash('sha256').update(bytes).digest('hex');

async function inventory(root: string): Promise<Record<string, string>> {
  const paths = await readdir(root, { recursive: true });
  const files: Record<string, string> = {};
  for (const path of paths.sort()) {
    const absolute = join(root, path);
    if ((await lstat(absolute)).isFile()) files[path] = digest(await readFile(absolute));
  }
  return files;
}

// The old renderer is deliberately used only here to generate an actual profile.
// eslint-disable-next-line no-empty-pattern
test('opens a profile generated by the previous package with obsolete Minecraft data present', async ({}, testInfo) => {
  const oldExecutable = process.env.DESKPET_PREVIOUS_PACKAGED_APP;
  const newExecutable = process.env.DESKPET_PACKAGED_APP;
  test.skip(process.platform !== 'darwin' || !oldExecutable || !newExecutable, 'Both exact macOS packages are required.');
  test.setTimeout(130_000);
  const root = await realpath(await mkdtemp(join(tmpdir(), 'deskpet-minecraft-retirement-')));
  const profile = join(root, 'profile');
  const legacyRoot = join(profile, 'minecraft');
  const taskId = randomUUID();
  const env: Record<string, string> = {};
  for (const key of ['PATH', 'HOME', 'TMPDIR', 'LANG', 'LC_ALL', 'DISPLAY']) {
    if (process.env[key]) env[key] = process.env[key]!;
  }
  let app: ElectronApplication | undefined;

  async function launch(executablePath: string, expectedAsar: string | undefined) {
    executablePath = await realpath(executablePath);
    const asar = resolve(dirname(executablePath), '../Resources/app.asar');
    expect(expectedAsar).toMatch(/^[a-f0-9]{64}$/u);
    expect(digest(await readFile(asar))).toBe(expectedAsar);
    app = await electron.launch({ executablePath, env, args: ['--use-mock-keychain', `--deskpet-isolated-profile=${root}`], timeout: 40_000 });
    expect(await app.evaluate(({ app }) => ({
      profile: app.getPath('userData'), packaged: app.isPackaged, asar: app.getAppPath(),
    }))).toEqual({ profile, packaged: true, asar });
    await expect.poll(() => app?.windows().some(window => window.url().includes('/main_window/'))).toBe(true);
    const page = app.windows().find(window => window.url().includes('/main_window/'))!;
    await expect(page.locator('.app-shell')).toBeVisible();
    return page;
  }

  try {
    await writeFile(join(root, 'isolated-candidate.json'), JSON.stringify({ version: 1, purpose: 'deskpet-isolated-candidate' }), { mode: 0o600 });
    let page = await launch(oldExecutable!, process.env.DESKPET_PREVIOUS_ASAR_SHA256);
    await page.evaluate(async id => {
      await window.deskpet.app.setTheme('dark');
      await window.deskpet.tasks.upsert({ id, title: 'Retirement fixture task', notes: '', status: 'todo', dueAt: null });
    }, taskId);
    const listener = createServer();
    await new Promise<void>((done, reject) => listener.once('error', reject).listen(0, '127.0.0.1', done));
    const address = listener.address();
    await new Promise<void>((done, reject) => listener.close(error => error ? reject(error) : done()));
    if (address === null || typeof address === 'string') throw new Error('Expected isolated loopback port.');
    await page.evaluate(async port => {
      type LegacyAPI = { connect(config: unknown): Promise<unknown>; getState(): Promise<{ lastError: string | null }> };
      const { minecraft } = window.deskpet as unknown as { minecraft: LegacyAPI };
      await minecraft.connect({ host: '127.0.0.1', port, username: 'RetiredFixture', version: '1.21.8',
        auth: 'offline', ownerName: 'FixtureOwner', executorMode: 'strict', providerId: null });
    }, address.port);
    await expect.poll(() => page.evaluate(async () => {
      const { minecraft } = window.deskpet as unknown as { minecraft: { getState(): Promise<{ lastError: string | null }> } };
      return (await minecraft.getState()).lastError;
    })).toMatch(/ECONNREFUSED/u);
    await app!.close();
    app = undefined;
    expect((await lstat(legacyRoot)).isDirectory()).toBe(true);
    // A refused connection creates the namespace but does not save learning.
    // Generate the learning sample with the installed package's own serializer.
    const oldResources = resolve(dirname(await realpath(oldExecutable!)), '../Resources');
    const oldRequire = createRequire(join(oldResources, 'minecraft-runtime', 'package.json'));
    const { createLearningStateStore } = oldRequire('./vendor/server/minecraft/learningStore.js') as {
      createLearningStateStore(options: { learningStatePath: string }): {
        load(): { state: { builds: { smallHouseScalePenalty: number } } };
        scheduleSave(state: unknown): void;
        flush(): boolean;
      };
    };
    const learning = createLearningStateStore({ learningStatePath: join(legacyRoot, 'minecraft-agent-learning.json') });
    const { state: learnedState } = learning.load();
    learnedState.builds.smallHouseScalePenalty = 1;
    learning.scheduleSave(learnedState);
    expect(learning.flush()).toBe(true);
    const legacyArtifacts = await inventory(legacyRoot);
    expect(legacyArtifacts).toHaveProperty(['minecraft-agent-learning.json']);

    page = await launch(newExecutable!, process.env.DESKPET_EXPECTED_ASAR_SHA256);
    expect(await page.evaluate(async id => ({
      preserved: (await window.deskpet.tasks.list()).some(task => task.id === id && task.title === 'Retirement fixture task'),
      theme: (await window.deskpet.app.getState()).theme,
      hasRetiredApi: Object.hasOwn(window.deskpet, 'minecraft'),
      companionState: await window.deskpet.minecraftCompanion!.getState(),
    }), taskId)).toMatchObject({ preserved: true, theme: 'dark', hasRetiredApi: false,
      companionState: { runtimeState: 'stopped', connectionState: 'disconnected', config: null, auth: null } });
    await app!.close();
    app = undefined;
    expect(await inventory(legacyRoot)).toEqual(legacyArtifacts);
    const evidence = testInfo.outputPath('profile-compatibility.json');
    await mkdir(dirname(evidence), { recursive: true });
    await writeFile(evidence, JSON.stringify({
      oldAppASARSHA256: process.env.DESKPET_PREVIOUS_ASAR_SHA256,
      newAppASARSHA256: process.env.DESKPET_EXPECTED_ASAR_SHA256,
      legacyArtifacts, encryptedTaskReadBack: true, preferenceReadBack: true, legacyApiAbsent: true,
    }, null, 2) + '\n');
    await testInfo.attach('profile-compatibility', { contentType: 'application/json', path: evidence });
  } finally {
    await app?.close().catch(() => undefined);
    await rm(root, { recursive: true, force: true });
  }
});
