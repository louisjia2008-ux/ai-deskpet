const invoke = <T, C extends InvokeChannel>(channel: C, payload: InvokePayload<C>): Promise<T> =>
  ipcRenderer.invoke(channel, { version: API_VERSION, payload }) as Promise<T>;

const on = <T>(channel: EventChannel, listener: (value: T) => void): Unsubscribe => {
  const handler = (_event: Electron.IpcRendererEvent, value: unknown): void => listener(value as T);
  ipcRenderer.on(channel, handler);
  return () => ipcRenderer.removeListener(channel, handler);
};

// Keep a tray navigation request until React has subscribed after window load.
const attentionOpenListeners = new Set<() => void>();
let attentionOpenPending = false;
ipcRenderer.on('attention:open-requested', () => {
  if (attentionOpenListeners.size === 0) attentionOpenPending = true;
  else for (const listener of attentionOpenListeners) listener();
});

